#!/usr/bin/env node
/**
 * Bring a shop's OWN product photography into the repo.
 *
 * scripts/build-media.mjs handles the source theme's borrowed furniture. This
 * handles the opposite: pictures of what the shop actually sells. They land
 * under public/img/own/, which is the one path isPlaceholderMedia does not
 * flag, so a shop showing them can go live.
 *
 * Same discipline as the theme imagery — a width ladder per file and a
 * generated map, so a srcset can never offer a width the build did not write.
 * Never upscales: a rung wider than the source is the same pixels in a bigger
 * file, and its `w` descriptor would be a lie the browser acts on.
 *
 *   node scripts/build-own-media.mjs <shop> <model-slug> <source-dir>
 *
 * Output is committed, so this runs when photography changes, not per build.
 */

import fs from "node:fs";
import path from "node:path";
import sharp from "sharp";

const [shop, slug, src] = process.argv.slice(2);
if (!shop || !slug || !src || !fs.existsSync(src)) {
  console.error("usage: node scripts/build-own-media.mjs <shop> <model-slug> <source-dir>");
  process.exit(1);
}

/**
 * The widths a product frame actually paints. The PDP gallery column is about
 * 700px at 1440 and the cross-sell cards about 400, so 400 and 800 cover both
 * at 1x; anything above that is capped by the source, which these are.
 */
const LADDER = [400, 800, 1200];
const QUALITY = 80;

const OUT = path.join(process.cwd(), "public", "img", "own", shop, slug);
fs.mkdirSync(OUT, { recursive: true });
for (const f of fs.readdirSync(OUT)) fs.unlinkSync(path.join(OUT, f));

/** Natural sort, so zr801-10 comes after zr801-9 rather than after zr801-1. */
const files = fs
  .readdirSync(src)
  .filter((f) => /\.(webp|jpe?g|png)$/i.test(f))
  .sort((a, b) =>
    a.localeCompare(b, undefined, { numeric: true, sensitivity: "base" }),
  );

if (files.length === 0) {
  console.error("no images in " + src);
  process.exit(1);
}

const entries = [];
let before = 0;
let after = 0;

for (const f of files) {
  const from = path.join(src, f);
  const meta = await sharp(from).metadata();
  const stem = path.parse(f).name.toLowerCase().replace(/[^a-z0-9-]+/g, "-");

  const cap = Math.min(Math.max(...LADDER), meta.width);
  const written = [];

  const encode = async (width, file) => {
    const info = await sharp(from)
      .resize({ width, withoutEnlargement: true })
      .webp({ quality: QUALITY })
      .toFile(path.join(OUT, file));
    after += fs.statSync(path.join(OUT, file)).size;
    return info.width;
  };

  // The master keeps the bare name and is the srcset fallback.
  const masterName = stem + ".webp";
  const masterWidth = await encode(cap, masterName);
  written.push(masterWidth);
  for (const w of LADDER) {
    if (w >= cap) continue;
    written.push(await encode(w, stem + "-" + w + ".webp"));
  }
  written.sort((a, b) => a - b);

  before += fs.statSync(from).size;
  const height = Math.round((meta.height / meta.width) * masterWidth);
  entries.push({ stem, masterName, masterWidth, height, written });
}

// --- the generated module ---------------------------------------------------
const MODULE = path.join(process.cwd(), "src", "themes", "studio", "own-media.ts");
const key = shop + "/" + slug;

/** Keep any other model's entries; replace only this one. */
let existing = {};
if (fs.existsSync(MODULE)) {
  const prev = fs.readFileSync(MODULE, "utf8");
  const start = prev.indexOf("= {");
  const end = prev.lastIndexOf("};");
  if (start > 0 && end > start) {
    try {
      existing = eval("(" + prev.slice(start + 2, end + 1) + ")");
    } catch {
      existing = {};
    }
  }
}

existing[key] = entries.map((e) => ({
  src: "/img/own/" + shop + "/" + slug + "/" + e.masterName,
  w: e.masterWidth,
  h: e.height,
  widths: e.written.map((w) => [
    "/img/own/" + shop + "/" + slug + "/" +
      (w === e.masterWidth ? e.masterName : e.stem + "-" + w + ".webp"),
    w,
  ]),
}));

const body = Object.keys(existing)
  .sort()
  .map((k) => {
    const rows = existing[k]
      .map(
        (p) =>
          "    {\n" +
          '      src: "' + p.src + '",\n' +
          "      w: " + p.w + ",\n" +
          "      h: " + p.h + ",\n" +
          "      widths: [" +
          p.widths.map((r) => '["' + r[0] + '", ' + r[1] + "]").join(", ") +
          "],\n" +
          "    },",
      )
      .join("\n");
    return '  "' + k + '": [\n' + rows + "\n  ],";
  })
  .join("\n");

fs.writeFileSync(
  MODULE,
  [
    "/**",
    " * GENERATED by scripts/build-own-media.mjs — do not edit.",
    " *",
    " * A shop's OWN product photography, keyed by \"<shop>/<model-slug>\", in the",
    " * order the gallery shows it. Everything here lives under /img/own/, which",
    " * is the path isPlaceholderMedia deliberately does not flag: these are",
    " * pictures of what the shop sells, not the source theme's furniture.",
    " *",
    " * The widths are the ones actually written. Generated rather than",
    " * hand-kept because a srcset offering a width the build did not write is a",
    " * 404 the browser picks on purpose, and both failures are silent.",
    " */",
    "",
    "export interface OwnPhoto {",
    "  readonly src: string;",
    "  readonly w: number;",
    "  readonly h: number;",
    "  /** [file, intrinsic width] rungs, narrowest first. */",
    "  readonly widths: readonly (readonly [string, number])[];",
    "}",
    "",
    "export const OWN_MEDIA: Readonly<Record<string, readonly OwnPhoto[]>> = {",
    body,
    "};",
    "",
  ].join("\n"),
);

const kb = (n) => (n / 1024).toFixed(0) + " KB";
console.log(
  files.length + " photos for " + key + "  " + kb(before) + " -> " + kb(after),
);
console.log("wrote " + path.relative(process.cwd(), OUT) + " and src/themes/studio/own-media.ts");
