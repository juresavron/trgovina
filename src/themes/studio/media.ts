/**
 * Imagery the studio theme can paint, and the rules about what it may claim.
 *
 * THESE ARE PLACEHOLDERS, AND THE DISTINCTION MATTERS COMMERCIALLY.
 * The files come from the source theme's own asset bundle, which is a
 * FURNITURE store: sofas, dining chairs, beds, lamps. The shops on this
 * network sell saunas, cold plunge tubs, hot tubs, massage chairs, stone-resin
 * baths and billiard tables. A photograph of a dining chair is therefore fine
 * as atmosphere and fine as scaffolding while a shop is pre-live — and is not
 * fine as the picture of the thing a customer is paying €1,500–15,000 for.
 *
 * So the media splits by what a slot CLAIMS:
 *
 *   motif / scene / room  — atmosphere. A room interior beside a buying guide
 *                           claims nothing about the product, exactly as
 *                           lifestyle photography does on any storefront.
 *   cutout / tile         — PRODUCT SLOTS. These carry the implication "this
 *                           is what you are buying", so the furniture cutouts
 *                           are NOT wired into them. Product slots keep their
 *                           drawn placeholder until the shop's own photography
 *                           exists.
 *
 * `isPlaceholderMedia` backs a launch gate: a shop cannot flip `live: true`
 * while any of this is still on the page. See src/tenants/media.test.ts.
 */

import { MEDIA_WIDTHS } from "./media-widths";

/** Everything under /img is generated by scripts/build-media.mjs. */
const BASE = "/img/";

/**
 * THE SHOP'S OWN PHOTOGRAPHY, as opposed to the source theme's bundle.
 *
 * Everything else in this module is borrowed furniture: fine as atmosphere,
 * never as a picture of the goods, and the launch gate below refuses to let a
 * shop go live while any of it is on the page. Files under /img/own/ are the
 * exception — they are pictures of what the shop actually sells, so they do
 * not trip the gate and they do not carry "simbolična fotografija".
 *
 * Putting them in the repo rather than in Supabase is deliberate for the hero
 * specifically: it is the LCP element on the page the whole SEO strategy
 * rests on, and a versioned file served from the edge before the Worker even
 * runs is a shorter path than a proxied object. Model photography belongs in
 * Supabase, through the admin panel, where it can change without a deploy.
 */
const OWN = BASE + "own/";

export interface Media {
  /** Path served by the Worker's static-asset binding. */
  readonly src: string;
  /**
   * Intrinsic size, so every slot can reserve space and CLS stays at zero —
   * the budget in docs/SEO.md §4 is a gate, not an aspiration.
   */
  readonly w: number;
  readonly h: number;
}

const m = (file: string, w: number, h: number): Media => ({ src: BASE + file, w, h });

