/**
 * Deterministic pick, so a shop's imagery is stable across renders and two
 * shops on the same theme do not land on the same picture. Not random: a page
 * that reshuffles its photography on every request is a page that looks broken
 * to anyone who reloads.
 */
export function pick<T>(list: readonly T[], seed: string, offset = 0): T {
  let h = 0;
  for (let i = 0; i < seed.length; i++) h = (h * 31 + seed.charCodeAt(i)) >>> 0;
  return list[(h + offset) % list.length] as T;
}

/**
 * True for any media this module can serve. The launch gate uses it: none of
 * this is the shop's own photography, so a live shop showing it is showing a
 * stranger's furniture.
 */
export function isPlaceholderMedia(src: string): boolean {
  return src.startsWith(BASE) && !src.startsWith(OWN);
}

/**
 * A shop's own hero photograph, where one exists.
 *
 * Empty until the files are in the repo. Adding one is a single entry here
 * plus the file under public/img/own/ — the hero then uses it instead of a
 * borrowed room, and drops the "simbolična fotografija" line, because the
 * picture is no longer symbolic of anything: it is the product.
 *
 * A photograph may only be listed against the shop that sells what is in it.
 * A hot tub is the bazen shop's; putting it on the sauna shop would be the
 * same error as the furniture, made with better pictures.
 */
export const SHOP_HERO: Readonly<Partial<Record<string, Media>>> = {
  // bazen: m("own/bazen-hero.webp", 1920, 623),
};

/**
 * The width ladder for a master file, as `srcset` syntax, or "" when the build
 * wrote only one width (the cutouts, and any source too small to ladder).
 */
function srcset(src: string): string {
  const rungs = MEDIA_WIDTHS[src.slice(BASE.length)];
  if (!rungs || rungs.length < 2) return "";
  return rungs.map((r) => BASE + r[0] + " " + r[1] + "w").join(", ");
}

/**
 * A picture that decorates rather than informs. Marked aria-hidden and given
 * an empty alt: a screen reader announcing "living room interior" beside a
 * sauna guide would be describing scaffolding as if it were content.
 *
 * `sizes` is only emitted alongside a `srcset`. For a long time it was emitted
 * on its own, which does nothing at all — every slot was handed the 1600px or
 * 1920px master whatever it painted, so a 437px guide card downloaded ~100 KB
 * to show ~13 KB of pixels, eight times down the home page. The attribute
 * looked like responsive images and was inert.
 */
export function decorativeImg(media: Media, cls: string, sizes: string): string {
  const set = srcset(media.src);
  return (
    '<img class="' + cls + '" src="' + media.src + '"' +
    (set ? ' srcset="' + set + '" sizes="' + sizes + '"' : "") +
    ' width="' + media.w + '" height="' + media.h + '"' +
    ' loading="lazy" decoding="async" alt="" aria-hidden="true">'
  );
}
